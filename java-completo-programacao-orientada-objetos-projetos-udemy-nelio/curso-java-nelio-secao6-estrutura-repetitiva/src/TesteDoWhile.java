
public class TesteDoWhile {

	public static void main(String[] args) {

		int x = 0;
		System.out.println(
				"Na estrutura de repeticao do-while, entra pelo menos uma vez, tal como for observando a condicao inicial, diferente da estrutura while");
		do {
			x++;
			System.out.println(x);
		} while (x < 5);

	}

}
